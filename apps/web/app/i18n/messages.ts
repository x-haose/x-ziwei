/** 把 `{name}` 占位换成值；文案里有占位而 `values` 没给，属于调用方写错，直接抛错。 */
export function fmt(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const v = values[key];
    if (v === undefined) throw new Error(`文案占位 {${key}} 没有给值：${template}`);
    return String(v);
  });
}
